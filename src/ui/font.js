export const GLYPH_W = 3, GLYPH_H = 5;

export function textWidth(text, size = 1) {
  return text.length * (GLYPH_W + 1) * size - size;
}

// Draws text with its top-left at (x, y); `u` is the screen size of one font pixel.
export function drawText(ctx, text, x, y, u, color, shadow = '#050604') {
  text = String(text).toUpperCase();
  for (const [col, ox, oy] of shadow ? [[shadow, 0, u], [color, 0, 0]] : [[color, 0, 0]]) {
    ctx.fillStyle = col;
    let cx = x + ox;
    for (const ch of text) {
      const bits = GLYPHS[ch] ?? GLYPHS[' '];
      for (let i = 0; i < 15; i++) if (bits[i] === '1') ctx.fillRect(cx + (i % 3) * u, y + oy + ((i / 3) | 0) * u, u, u);
      cx += (GLYPH_W + 1) * u;
    }
  }
}

